export const EXCLUDE_UNAVAILABLE_PORTS = true;

// 返却枠に制限が無いポートを見分けるしきい値。
//
// 横浜市内には、ドコモ・バイクシェアが運営していて HELLO CYCLING からも使えるポートがある
// （名前が「116.横浜駅西口第２駐車場」のように番号で始まる 26 か所）。駐車場や公園の一角で、
// 自転車を停めるラックが無いため、返せる台数に実質的な上限が無い。
//
// GBFS v2.3 は「無制限のポートでは num_docks_available を省略してよい」と定めているが、
// 両社ともこれを使わず全ポートに数値を入れている（is_virtual_station も両社とも 0 件）。
//   HELLO CYCLING … 定員 1000・空き 991 のように、十分大きい値を返す
//   ドコモ         … ポートごとに固定の数を空きとして返す
// 2026-10-09 に 35 分間 3 回測ると、カップヌードルミュージアムは台数 37→34→33 と動いたのに
// 空きは 18 のままだった。
//
// なお、ドコモの空き台数はこの 26 か所に限らずフィード全体で当てにならない。全 6157 ポートで
// 「空き ＝ 定員 − 自社台数」が 100% 成立していて、定員は逆算された派生値。本物のラックなら
// 自転車が 1 台出れば空きが 1 台増えて定員は変わらないはずだが、台数が動いた 1829 ポートの
// うちそうなったのは 29.4% だけで、59.5% は台数が動いても空きが固定だった。
// 26 か所が違うのは程度だけ（25 分で空きが動いたのは、ふつうのポート 17.6% に対し 0 件）。
// このため空きの判定には HELLO CYCLING 側だけを使っている（TRUSTED_DOCKS_PROVIDER）。
//
// ドコモの空き 0 を「満」と読んではいけない。ラックが無いポートでは空きラック数が 0 に
// なるだけで、アプリ上は上限なく「返却可能」と出る（オーケーみなとみらいで確認）。
//
// そこで、このしきい値を超えるポートでは**空き台数を使わず、返せるかどうかの印だけを見る**。
// 案内券にも数字ではなく「空きあり」と出す。
//
// 100 にしたのは、HELLO のフィード全 15,394 ポートのうち空きが 100 以上なのが
// ちょうどこの 26 か所だけだったため（同日確認）。定員は station_information 側にしか
// 無く、検索では取っていないので、空き台数から見分けている。
export const RETURN_CAPACITY_UNKNOWN_DOCKS = 100;

// 閉店前にどれだけ余裕を見るか（分、#47）。
